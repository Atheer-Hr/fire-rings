export const lang = () => LANG;
export function setLang(l) {
  LANG = l;
  try { localStorage.setItem("fr-lang", l); } catch { /* ignore */ }
}
export function t(key, vars = {}) {
  let s = S[LANG][key] ?? S.en[key] ?? key;
  if (typeof s !== "string") return s;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
// Fill every element with data-i18n="key" (html) or data-i18n-title / data-i18n-aria.
export function applyStatic() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = S[LANG].dir;
  document.title = S[LANG].title;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.innerHTML = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
}
